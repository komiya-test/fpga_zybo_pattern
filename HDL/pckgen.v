/*
 * ピクセルクロック生成回路
 *
 * 125MHzのシステムクロック（SYSCLK）から、
 * VGAで使用する約25.175MHzのクロック（PCK）を作る。
 *
 *
 *   125MHz
 *      │
 *      ▼
 *   ┌─────────┐
 *   │  MMCM   │
 *   │         │
 *   │ 周波数  │
 *   │ 変換    │
 *   └────┬────┘
 *        │
 *        │ 約25.175MHz
 *        ▼
 *      BUFG
 *        │
 *        ▼
 *       PCK
 *
 *
 * MMCM
 *   → FPGA内部でクロックの周波数や位相を調整する回路
 *
 * BUFG
 *   → FPGA内部でクロックを効率よく配るための
 *      専用バッファ
 *
 */

module pckgen (
    input   SYSCLK,     // 125MHzのシステムクロック
    output  PCK         // 約25.175MHzのピクセルクロック
);


/*------------------------------------------------------------
 * MMCM関連の信号
 *------------------------------------------------------------*/


/*
 * MMCM内部で作られるフィードバック用クロック。
 *
 * MMCMは、
 *
 *   入力クロック
 *       ↓
 *   周波数変換
 *       ↓
 *   出力クロック
 *
 * だけではなく、
 * 出力クロックを内部に戻して
 * クロックの状態を調整する。
 *
 * そのための信号がCLKFBOUT / CLKFBIN。
 */
wire CLKFBOUT;


/*
 * MMCMから出てきたピクセルクロック。
 *
 * まだBUFGを通す前なので、
 * 内部信号としてiPCKという名前にしている。
 */
wire iPCK;


/*
 * MMCMが正常に目的のクロック状態になったかを示す信号。
 *
 *   locked = 1
 *      → MMCMがロックした
 *
 *   locked = 0
 *      → まだロックしていない
 *
 * 今回の回路では、この信号は外部では使用していない。
 */
wire locked;


/*------------------------------------------------------------
 * BUFG
 *
 * MMCMから出てきたクロックを
 * FPGA内部のクロック配線へ乗せる。
 *
 * FPGAでは、普通の信号線でクロックを配るのではなく、
 * 専用のクロック配線を使用する。
 *
 *   iPCK
 *     ↓
 *   BUFG
 *     ↓
 *    PCK
 *
 *------------------------------------------------------------*/

BUFG iBUFG (
    .I(iPCK),      // BUFGへの入力
    .O(PCK)        // BUFGからの出力
);


/*============================================================
 * MMCM
 *============================================================
 *
 * Xilinx / AMD FPGAに用意されている
 * クロック生成用のプリミティブ。
 *
 * MMCME2_BASEを使って、
 *
 *   SYSCLK = 125MHz
 *
 * から
 *
 *   PCK ≒ 25.175MHz
 *
 * を作る。
 *
 *------------------------------------------------------------*/

MMCME2_BASE #(

    /*
     * MMCMの動作モード。
     *
     * 基本的にはOPTIMIZEDを使用。
     *
     * 今は「MMCMの内部設定の一つ」
     * くらいに考えてOK。
     */
    .BANDWIDTH("OPTIMIZED"),


    /*--------------------------------------------------------
     * MMCMの周波数計算に関係する設定
     *--------------------------------------------------------*/


    /*
     * VCO側のクロックを作るための倍率 M。
     *
     * 今回は36倍。
     *
     * 入力125MHzに対して、
     *
     *   125MHz / 5 × 36
     *   = 900MHz
     *
     * という内部クロックを作る。
     *
     * ※MMCMでは、入力クロックをそのまま
     *   36倍するのではなく、
     *   DIVCLK_DIVIDEによる分周も入る。
     */
    .CLKFBOUT_MULT_F(36.0),


    /*
     * フィードバッククロックの位相。
     *
     * 0度なので、基本的に位相をずらさない。
     */
    .CLKFBOUT_PHASE(0.0),


    /*
     * 入力クロックの周期。
     *
     * SYSCLK = 125MHzなので、
     *
     *   1 / 125MHz = 8ns
     *
     * よって8.0ns。
     */
    .CLKIN1_PERIOD(8.0),


    /*--------------------------------------------------------
     * CLKOUT1～CLKOUT6
     *
     * MMCMには複数の出力クロックを作る機能がある。
     *
     * 今回実際に使用しているのはCLKOUT0だけ。
     *
     * そのため、CLKOUT1～6は使用していない。
     *--------------------------------------------------------*/

    .CLKOUT1_DIVIDE(1),
    .CLKOUT2_DIVIDE(1),
    .CLKOUT3_DIVIDE(1),
    .CLKOUT4_DIVIDE(1),
    .CLKOUT5_DIVIDE(1),
    .CLKOUT6_DIVIDE(1),


    /*--------------------------------------------------------
     * CLKOUT0の分周値
     *
     * ここがPCKの周波数を決める重要な値。
     *
     * MMCM内部のVCO周波数を、
     * CLKOUT0_DIVIDE_Fで分周して
     * iPCKを作る。
     *
     * 今回は35.75。
     *
     *--------------------------------------------------------*/

    .CLKOUT0_DIVIDE_F(35.75),


    /*--------------------------------------------------------
     * クロックのデューティ比
     *
     * 0.5 = 50%
     *
     * つまり、
     *
     *   HIGH 50%
     *   LOW  50%
     *
     * のほぼ矩形波にする。
     *--------------------------------------------------------*/

    .CLKOUT0_DUTY_CYCLE(0.5),

    /*
     * 今回使わないCLKOUT1～6も
     * デューティ比を50%に設定している。
     */
    .CLKOUT1_DUTY_CYCLE(0.5),
    .CLKOUT2_DUTY_CYCLE(0.5),
    .CLKOUT3_DUTY_CYCLE(0.5),
    .CLKOUT4_DUTY_CYCLE(0.5),
    .CLKOUT5_DUTY_CYCLE(0.5),
    .CLKOUT6_DUTY_CYCLE(0.5),


    /*--------------------------------------------------------
     * 各出力クロックの位相
     *
     * 0度なので、位相をずらさない。
     *--------------------------------------------------------*/

    .CLKOUT0_PHASE(0.0),
    .CLKOUT1_PHASE(0.0),
    .CLKOUT2_PHASE(0.0),
    .CLKOUT3_PHASE(0.0),
    .CLKOUT4_PHASE(0.0),
    .CLKOUT5_PHASE(0.0),
    .CLKOUT6_PHASE(0.0),


    /*
     * CLKOUT4とCLKOUT6をカスケード接続するか。
     *
     * 今回は使用しないのでFALSE。
     */
    .CLKOUT4_CASCADE("FALSE"),


    /*--------------------------------------------------------
     * 入力クロックを分周する値 D
     *
     * 今回は5。
     *
     * SYSCLK = 125MHzなので、
     *
     *   125MHz / 5
     *   = 25MHz
     *
     * ではなく、
     *
     * MMCM内部ではこの後M=36倍するため、
     *
     *   125 / 5 × 36
     *   = 900MHz
     *
     * というVCOクロックを作る。
     *--------------------------------------------------------*/

    .DIVCLK_DIVIDE(5),


    /*
     * 入力クロックのジッタに関する設定。
     *
     * 今回は0.0。
     *
     * 初心者の段階では、
     * 「クロックの揺らぎに関する設定」
     * と理解しておけばOK。
     */
    .REF_JITTER1(0.0),


    /*
     * MMCMがロックするまでFPGAのDONE信号を
     * 遅らせるかどうか。
     *
     * 今回はFALSE。
     */
    .STARTUP_WAIT("FALSE")

)


/*------------------------------------------------------------
 * MMCM本体のインスタンス名
 *------------------------------------------------------------*/

MMCME2_BASE_inst (

    /*--------------------------------------------------------
     * クロック出力
     *--------------------------------------------------------*/

    /*
     * CLKOUT0から約25.175MHzのクロックを出力。
     *
     * このクロックをiPCKに接続する。
     */
    .CLKOUT0(iPCK),


    /*
     * CLKOUT0の反転出力。
     *
     * 今回は使用しない。
     */
    .CLKOUT0B(),


    /*
     * CLKOUT1～6
     *
     * 今回は使用しないので、
     * 出力先を空欄にしている。
     */
    .CLKOUT1(),
    .CLKOUT1B(),
    .CLKOUT2(),
    .CLKOUT2B(),
    .CLKOUT3(),
    .CLKOUT3B(),
    .CLKOUT4(),
    .CLKOUT5(),
    .CLKOUT6(),


    /*--------------------------------------------------------
     * フィードバッククロック
     *--------------------------------------------------------*/

    /*
     * MMCMから出たフィードバッククロック。
     */
    .CLKFBOUT(CLKFBOUT),

    /*
     * 反転したフィードバッククロック。
     *
     * 今回は使用しない。
     */
    .CLKFBOUTB(),


    /*--------------------------------------------------------
     * MMCMの状態
     *--------------------------------------------------------*/

    /*
     * MMCMが目的のクロック状態に
     * ロックしたかどうか。
     */
    .LOCKED(locked),


    /*--------------------------------------------------------
     * クロック入力
     *--------------------------------------------------------*/

    /*
     * 125MHzのシステムクロックを入力。
     */
    .CLKIN1(SYSCLK),


    /*--------------------------------------------------------
     * 制御信号
     *--------------------------------------------------------*/

    /*
     * 1にするとMMCMを停止状態にする。
     *
     * 今回は0なので通常動作。
     */
    .PWRDWN(1'b0),


    /*
     * MMCMのリセット。
     *
     * 今回は0なのでリセットしていない。
     */
    .RST(1'b0),


    /*--------------------------------------------------------
     * フィードバック入力
     *--------------------------------------------------------*/

    /*
     * MMCMのCLKFBOUTを、
     * CLKFBINへ戻している。
     *
     * これがMMCMのフィードバック経路。
     *
     *       CLKFBOUT
     *           │
     *           └────────→ CLKFBIN
     *
     */
    .CLKFBIN(CLKFBOUT)

);

endmodule