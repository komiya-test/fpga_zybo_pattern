/*
 * VGA同期信号生成モジュール
 *
 * このモジュールの仕事は、
 *
 *   ① 125MHzのCLKからPCKを作る
 *   ② PCKに合わせてHCNTを数える
 *   ③ HCNTが1ライン終わったらVCNTを1増やす
 *   ④ HCNT / VCNTを使ってVGA_HSを作る
 *   ⑤ HCNT / VCNTを使ってVGA_VSを作る
 *
 * ということ。
 *
 *
 * 全体イメージ
 *
 *                 PCK
 *                  │
 *                  ▼
 *          ┌───────────────┐
 *          │    HCNT       │
 *          │ 0 → 799 → 0  │
 *          └───────┬───────┘
 *                  │
 *             1ライン終了
 *                  │
 *                  ▼
 *          ┌───────────────┐
 *          │    VCNT       │
 *          │ 0 → 524 → 0  │
 *          └───────┬───────┘
 *                  │
 *                  ▼
 *        VGA_HS / VGA_VS
 *
 */


/*============================================================
 * モジュールの入出力
 *============================================================*/

module syncgen(
    input               CLK,       // FPGAから入ってくる125MHzクロック
    input               RST,       // リセット

    output              PCK,       // VGA用ピクセルクロック

    output  reg         VGA_HS,    // 水平同期信号
    output  reg         VGA_VS,    // 垂直同期信号

    output  reg [9:0]   HCNT,      // 水平方向の位置
    output  reg [9:0]   VCNT       // 垂直方向の位置
);


/*------------------------------------------------------------
 * VGAのタイミングパラメータを読み込む
 *
 * vga_param.vhには、
 *
 *   HPERIOD = 800
 *   HFRONT  = 16
 *   HWIDTH  = 96
 *   HBACK   = 48
 *
 *   VPERIOD = 525
 *   VFRONT  = 10
 *   VWIDTH  = 2
 *   VBACK   = 33
 *
 * が定義されている。
 *
 *------------------------------------------------------------*/

`include "vga_param.vh"


/*------------------------------------------------------------
 * VGA用のピクセルクロックPCKを作る
 *
 * pckgenの中でMMCMを使って、
 *
 *   CLK = 125MHz
 *        ↓
 *   PCK ≒ 25.175MHz
 *
 * に変換している。
 *
 *------------------------------------------------------------*/

pckgen pckgen (
    .SYSCLK(CLK),
    .PCK(PCK)
);


/*============================================================
 * 水平方向カウンタ HCNT
 *============================================================
 *
 * HCNTは、
 *
 *   0 → 1 → 2 → 3 → ... → 798 → 799 → 0 → ...
 *
 * と増えていく。
 *
 * HPERIOD = 800なので、
 * 1ラインを800クロックでカウントする。
 *
 *
 * イメージ
 *
 * HCNT
 *
 * 0       1       2                  799
 * │       │       │                   │
 * ▼       ▼       ▼                   ▼
 * ├───────┴───────┴──・・・────────────┤
 *                                     │
 *                                     └→ 次のラインへ
 *
 *------------------------------------------------------------*/


/*
 * HCNTが最後の値まで到達したかを判定。
 *
 * HPERIOD = 800なので、
 *
 *   HPERIOD - 1 = 799
 *
 * HCNT == 799
 *
 * になったら1ライン終了。
 */
wire hcntend = (HCNT == HPERIOD - 10'h001);


/*
 * PCKの立ち上がりごとにHCNTを更新する。
 *
 * つまり約25.175MHzの速さで
 * HCNTが1ずつ増えていく。
 */
always @(posedge PCK) begin

    /* リセットされたら0に戻す */
    if (RST)

        HCNT <= 10'h000;


    /*
     * 1ラインの最後まで来たら、
     * 次のラインの先頭なので0に戻す。
     */
    else if (hcntend)

        HCNT <= 10'h000;


    /*
     * それ以外は1増やす。
     */
    else

        HCNT <= HCNT + 10'h001;

end


/*============================================================
 * 垂直方向カウンタ VCNT
 *============================================================
 *
 * VCNTは「現在何ライン目なのか」を表す。
 *
 * HCNTが1ライン終了したときだけ、
 * VCNTを1増やす。
 *
 *
 *   HCNT
 *   0 → 799
 *       ↓
 *   VCNT + 1
 *
 *
 * VPERIOD = 525なので、
 *
 *   0 → 1 → 2 → ... → 523 → 524 → 0
 *
 * と動く。
 *
 *------------------------------------------------------------*/


always @(posedge PCK) begin

    /* リセットされたら0ライン目 */
    if (RST)

        VCNT <= 10'h000;


    /*
     * 1ライン終了したときだけ、
     * VCNTを更新する。
     */
    else if (hcntend) begin

        /*
         * 525ライン目（VCNT=524）が終わったら
         * 次の画面になるので0に戻す。
         */
        if (VCNT == VPERIOD - 10'h001)

            VCNT <= 10'h000;

        /*
         * まだ画面の途中なら
         * 次のラインへ進む。
         */
        else

            VCNT <= VCNT + 10'h001;

    end

end


/*============================================================
 * VGA_HS / VGA_VSのタイミングを計算
 *============================================================
 *
 * VGAの同期信号は、
 * HCNT / VCNTの値を見てON/OFFする。
 *
 *------------------------------------------------------------*/


/*
 * 水平同期信号（VGA_HS）の開始位置
 *
 * HFRONT = 16なので、
 *
 *   hsstart = 16 - 1
 *           = 15
 *
 * HCNTが15になったところで
 * HSをLOWにする。
 */
wire [9:0] hsstart = HFRONT - 10'h001;


/*
 * 水平同期信号（VGA_HS）の終了位置
 *
 * HFRONT + HWIDTH - 1
 *
 * = 16 + 96 - 1
 * = 111
 *
 * HCNTが111になったところで
 * HSをHIGHに戻す。
 */
wire [9:0] hsend =
        HFRONT + HWIDTH - 10'h001;


/*
 * 垂直同期信号（VGA_VS）の開始ライン
 *
 * VFRONT = 10
 *
 * VCNTが10になったら、
 * VSをLOWにする。
 */
wire [9:0] vsstart = VFRONT;


/*
 * 垂直同期信号（VGA_VS）の終了ライン
 *
 * VFRONT + VWIDTH
 *
 * = 10 + 2
 * = 12
 *
 * VCNTが12になったら、
 * VSをHIGHに戻す。
 */
wire [9:0] vsend =
        VFRONT + VWIDTH;


/*============================================================
 * 水平同期信号 VGA_HS
 *============================================================
 *
 * VGA_HSは、
 * 「1ラインが終わって次のラインが始まる」
 * ことをモニタに知らせる信号。
 *
 *
 * 今回は、
 *
 *   HCNT = 15
 *       ↓
 *   HS = LOW
 *
 *   HCNT = 111
 *       ↓
 *   HS = HIGH
 *
 * となる。
 *
 *
 * HSのイメージ
 *
 * HCNT
 *
 *  0       15               111                 799
 *  │        │                │                   │
 *  ▼        ▼                ▼                   ▼
 *
 * HS ────────┐                ┌───────────────────
 *            │                │
 *            └────────────────┘
 *              96クロック
 *
 *------------------------------------------------------------*/


always @(posedge PCK) begin

    /*
     * リセット中はHSをHIGHにする。
     */
    if (RST)

        VGA_HS <= 1'b1;


    /*
     * HCNTがhsstartになったら
     * HSをLOWにする。
     */
    else if (HCNT == hsstart)

        VGA_HS <= 1'b0;


    /*
     * HCNTがhsendになったら
     * HSをHIGHに戻す。
     */
    else if (HCNT == hsend)

        VGA_HS <= 1'b1;

end


/*============================================================
 * 垂直同期信号 VGA_VS
 *============================================================
 *
 * VSは「1画面が終わって、
 * 次の画面が始まる」ことを知らせる信号。
 *
 * ただしVSは毎クロック変化するわけではない。
 *
 * 水平同期の開始位置
 *
 *   HCNT == hsstart
 *
 * のタイミングで、
 * VCNTをチェックしてVSを変化させている。
 *
 *------------------------------------------------------------*/


always @(posedge PCK) begin

    /*
     * リセット中はVSをHIGHにする。
     */
    if (RST)

        VGA_VS <= 1'b1;


    /*
     * 1ラインの開始位置付近で、
     * 現在のライン番号VCNTをチェックする。
     *
     * つまり、
     *
     * 「新しいラインが始まった瞬間に、
     *  今何ライン目なのかを見る」
     *
     * ということ。
     */
    else if (HCNT == hsstart) begin


        /*
         * VCNTが10になったら
         * 垂直同期開始。
         */
        if (VCNT == vsstart)

            VGA_VS <= 1'b0;


        /*
         * VCNTが12になったら
         * 垂直同期終了。
         */
        else if (VCNT == vsend)

            VGA_VS <= 1'b1;

    end

end


endmodule