/*
 * VGA表示用のパターン生成回路
 *
 * このモジュールでは、
 * 640×480画面にRGBの色パターンを表示する。
 *
 * 大まかな流れ
 *
 *   CLK
 *    ↓
 *   syncgen
 *    ↓
 *   PCK（VGA用のピクセルクロック）
 *    ↓
 *   HCNT / VCNT（現在の画面位置）
 *    ↓
 *   disp_enable（今、画面表示領域か？）
 *    ↓
 *   RGBの色を決める
 *    ↓
 *   VGA_R / VGA_G / VGA_B
 *
 */


/*------------------------------------------------------------
 * モジュールの入出力
 *------------------------------------------------------------*/

module pattern(
    input               CLK,       // FPGAの基本クロック
    input               RST,       // リセット信号
    output  reg [7:0]   VGA_R,     // VGAの赤色信号（8bit）
    output  reg [7:0]   VGA_G,     // VGAの緑色信号（8bit）
    output  reg [7:0]   VGA_B,     // VGAの青色信号（8bit）
    output              VGA_HS,    // 水平同期信号
    output              VGA_VS,    // 垂直同期信号
    output  reg         VGA_DE,    // 表示有効信号
    output              PCK        // VGA用ピクセルクロック
);


/*------------------------------------------------------------
 * VGAのタイミングパラメータ
 *
 * vga_param.vh の中に、
 * 640×480 VGAで使用する各種タイミングが定義されている。
 *
 * 例えば、
 *
 *   HFRONT : 水平方向のフロントポーチ
 *   HWIDTH : 水平同期信号の幅
 *   HBACK  : 水平方向のバックポーチ
 *
 * といった値が入っている。
 *
 * 「画面に表示する部分」以外にも、
 * VGAでは同期信号などのための時間が存在する。
 *
 *------------------------------------------------------------*/

`include "vga_param.vh"


/*------------------------------------------------------------
 * 1つの色ブロックの大きさ
 *
 * HSIZE = 80
 *   → 横方向80ピクセルごとに色を変える
 *
 * VSIZE = 120
 *   → 縦方向120ピクセルごとに色を変える
 *
 * 640 / 80 = 8
 *
 * つまり横方向には8個の色ブロックができる。
 *
 *------------------------------------------------------------*/

localparam HSIZE = 10'd80;
localparam VSIZE = 10'd120;


/*------------------------------------------------------------
 * 画面位置を表すカウンタ
 *
 * HCNT
 *   → 水平方向の現在位置
 *
 * VCNT
 *   → 垂直方向の現在位置
 *
 * 例えば、
 *
 *   HCNT = 0
 *   VCNT = 0
 *
 * なら、画面の左上付近。
 *
 * HCNTが増えていくと右方向へ進み、
 * HCNTが一周するとVCNTが1増えて、
 * 次の行へ進む。
 *
 *------------------------------------------------------------*/

wire [9:0] HCNT, VCNT;


/*------------------------------------------------------------
 * VGAの同期信号と画面位置カウンタを作る回路
 *
 * syncgenの中で、
 *
 *   PCK   → ピクセルクロック
 *   VGA_HS → 水平同期信号
 *   VGA_VS → 垂直同期信号
 *   HCNT  → 水平方向位置
 *   VCNT  → 垂直方向位置
 *
 * が生成される。
 *
 * このpatternモジュールでは、
 * 「今、画面の何ピクセル目なのか」を
 * HCNT / VCNTから知ることができる。
 *
 *------------------------------------------------------------*/

syncgen syncgen(
    .CLK    (CLK),
    .RST    (RST),
    .PCK    (PCK),
    .VGA_HS (VGA_HS),
    .VGA_VS (VGA_VS),
    .HCNT   (HCNT),
    .VCNT   (VCNT)
);


/*------------------------------------------------------------
 * 水平方向・垂直方向の「表示開始位置」を計算
 *
 * VGAの1行は、
 *
 *   フロントポーチ
 *   ＋ 水平同期
 *   ＋ バックポーチ
 *   ＋ 実際の画面
 *
 * という構成になっている。
 *
 * HBLANK
 *   → 実際の画面表示が始まる位置
 *
 * VBLANK
 *   → 実際の画面表示が始まる行
 *
 *------------------------------------------------------------*/

wire [9:0] HBLANK = HFRONT + HWIDTH + HBACK;
wire [9:0] VBLANK = VFRONT + VWIDTH + VBACK;


/*------------------------------------------------------------
 * disp_enable
 *
 * 「現在の位置が、実際に画像を表示する領域か？」
 * を判断する信号。
 *
 * 画面表示領域なら 1
 * それ以外なら 0
 *
 * VGAでは、同期信号などのために
 * 画面として使わない期間が存在する。
 *
 * そのため、HCNT / VCNTが画面表示領域に
 * 入っているかをチェックしている。
 *
 *------------------------------------------------------------*/

wire disp_enable =
        (VBLANK <= VCNT)
        &&
        (HBLANK-10'd1 <= HCNT)
        &&
        (HCNT < HPERIOD-10'd1);


/*------------------------------------------------------------
 * 横方向の色番号を決める
 *
 * HCNTから「画面の何番目の色ブロックか」を計算する。
 *
 * HSIZE = 80なので、
 *
 *   0～79     → 0
 *   80～159   → 1
 *   160～239  → 2
 *   ...
 *
 * となる。
 *
 * 640 / 80 = 8なので、
 * rgb_0は0～7の値になる。
 *
 *------------------------------------------------------------*/

wire [2:0] rgb_0 =
        (HCNT-HBLANK+10'd1) / HSIZE;


/*------------------------------------------------------------
 * 縦方向によって色の順番を反転させる
 *
 * VCNTから、
 * 「今、何番目の縦方向のブロックなのか」
 * を求めている。
 *
 * VSIZE = 120なので、
 *
 *   0～119       → 0
 *   120～239     → 1
 *   240～359     → 2
 *   ...
 *
 * となる。
 *
 * さらに、
 *
 *   縦ブロックが偶数 → 色番号を反転
 *   縦ブロックが奇数 → そのまま
 *
 * としている。
 *
 * 例えば、
 *
 *   rgb_0 = 0 のとき
 *       7 - 0 = 7
 *
 *   rgb_0 = 1 のとき
 *       7 - 1 = 6
 *
 * となる。
 *
 * これによって、隣の行で色の並びが
 * 反対になるパターンを作っている。
 *
 *------------------------------------------------------------*/

wire [2:0] rgb_1 =
        (((VCNT-VBLANK) / VSIZE) & 1) == 0
        ? 3'd7 - rgb_0
        : rgb_0;


/*------------------------------------------------------------
 * RGB信号を出力する
 *
 * PCKの立ち上がりごとに、
 * 現在の位置に対応するRGB値を出力する。
 *
 *------------------------------------------------------------*/

always @(posedge PCK) begin

    /* リセット中は黒を出力 */
    if (RST)

        {VGA_R, VGA_G, VGA_B} <= 24'h0;


    /* 画面表示領域なら色を出力 */
    else if (disp_enable)

        /*
         * rgb_1は3bit
         *
         *   rgb_1[2] → 赤
         *   rgb_1[1] → 緑
         *   rgb_1[0] → 青
         *
         * それぞれの1bitを8bitに拡張している。
         *
         * 例えば
         *
         *   rgb_1 = 3'b101
         *
         * なら
         *
         *   R = 8'hFF
         *   G = 8'h00
         *   B = 8'hFF
         *
         * となる。
         *
         * つまり、この3bitの値を使って
         * 8種類の色を作っている。
         */

        {VGA_R, VGA_G, VGA_B} <=
            {
                {8{rgb_1[2]}},    // R
                {8{rgb_1[1]}},    // G
                {8{rgb_1[0]}}     // B
            };


    /* 画面表示領域以外は黒 */
    else

        {VGA_R, VGA_G, VGA_B} <= 24'h0;

end


/*------------------------------------------------------------
 * VGA_DE（Display Enable）を作る
 *
 * disp_enableが
 *
 *   1 → 画面表示中
 *   0 → 画面表示領域外
 *
 * なので、基本的には
 *
 *   VGA_DE = disp_enable
 *
 * とすればよい。
 *
 * ここではPCKの立ち上がりに合わせて
 * VGA_DEを更新している。
 *
 *------------------------------------------------------------*/

always @(posedge PCK) begin

    /* リセット中は表示無効 */
    if (RST)

        VGA_DE <= 1'b0;

    /* 通常時はdisp_enableをそのまま出力 */
    else

        VGA_DE <= disp_enable;

end


endmodule